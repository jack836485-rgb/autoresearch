"""由 资料/问题卡/Q*.json 与 资料/查新/结论_*.json 生成 研究地图.md 的卡片部分；手写部分在本脚本的常量里。"""
import glob, json, os

slot = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cards = {os.path.basename(f)[:-5]: json.load(open(f, encoding="utf-8"))
         for f in sorted(glob.glob(f"{slot}/资料/问题卡/Q*.json"))}

推荐 = ["Q004", "Q060", "Q070", "Q067", "Q068", "Q045"]
理由 = {
    "Q004": "受控反常最干净：同 rollout、同随机奖励，只换学习者检查点，结果从 2.9 到 13.7 点；直接反驳“rollout 质量”解释。OLMo-2 的 mid-training 检查点公开，2×A100 可做预研。",
    "Q060": "把两套互相矛盾的无标签 RL 理论接到一个可测量的量上，并产出坍缩预警这一可用结果；Qwen3-1.7B 规模即可。",
    "Q070": "训练前预测 OPD 遗忘，填补 OPDArena 只做事后相关、只覆盖同基座教师的空白；可复用 OPDArena 的师生对，主要是前向计算。",
    "Q067": "推理评判器作奖励时正负号相反，奖励接口已被排除，剩优化器与评判器被骗两条解释；需小评判器训练与策略训练，算力中等。",
    "Q068": "新颖性奖励粒度假说有直接线索（RND 只奖励正确回答仍退化）；需要三种奖励各跑一次数学 RLVR，算力中等。",
    "Q045": "纯推理评测即可，成本最低；但唯一做了规避实验的模型恰好是抑制可控性提升最弱的 DeepSeek-R1，且有反向证据（2609.31121：训练压力下规避靠措辞而非隐藏信息），结论风险最高。",
}

头 = """# 近期分歧与反常：用并行查新筛出可送打磨的问题

检索日期：2026-11-06　｜　近期窗口：2026-08-06 至 2026-11-06（主证据越新越好）　｜　机构口径：ai-frontier-search 白名单或 QS 前 50（主证据论文至少一名作者）

## 摘要

上一张地图（`跨地图共性缺口_20261105`）的 30 张"跨载体共性"卡，事后逐卡查新只有 1 张不拥挤（旧地图的 Q026，已在打磨；与本地图编号相同的 Q026 无关）。这张地图换了两处做法：

1. **只找两类问题：** 近期论文之间的**待解释分歧**（相近设置、相反结论、无人对齐）和**反常结果**（更强/更多反而更差、干预换条件反号且原作未解释）。
2. **边找边查新：** 每写出一批卡，就交给并行的查新子代理做问题级拥挤度检查，结论写回卡上；判为偏拥挤、拥挤或前提不成立的卡，按子代理给出的"剩余空间"改写成更细的新卡再查。

结果：共 34 张卡（3 个找卡子任务写出 22 张原卡，主执行者由剩余空间改写 12 张），**6 张不拥挤**，全部可送 `/idea-improvement-loop`：

"""

教训 = """
## 一、这一轮学到的东西

- **原卡命中率低，改写卡命中率高。** 22 张原卡只有 2 张不拥挤（Q004、Q045）；12 张改写卡有 4 张不拥挤（Q060、Q067、Q068、Q070）。查新子代理读过近邻后给出的"剩余空间"，比找卡时的一次快速检索更能定位没人回答的那一小块。
- **"前提不成立"是原卡的主要死因（原卡 8/22，改写卡 0/12）。** 典型情形：两篇"相反"的论文其实测的不是同一个量（Q026：有害请求拒绝 vs 流程省略；Q040：编辑成合法状态 vs 改坏一步），或者结论方向一致、只是作者解读不同（Q047：两篇的斜率与截距符号一致，"敏感"与"不校准"可同时成立）。第三轮找卡说明里加了"先核对两组证据是否测的是同一个量"，但两张第三轮卡仍死于此，说明这一步需要片段级核对，摘要不够。
- **偏拥挤最常见的形态是"把两三篇近邻的变量放进同一设置比较"（16/34）。** 这类卡的子变量各自已有专门论文；能改写成不拥挤卡的，都是在剩余空间里找到了一个**新的可测量的量**（ρ̄ 的轨迹、训练前教师偏移、优化器这一未被扫描的轴），而不是再加一个对照。
- **第三轮找卡只看最近 5 周论文，3 个子任务只写出 2 张卡（Q026、Q047），都判前提不成立。** 新论文多，但够格的分歧少；继续加找卡人力的边际收益已经很低，剩余空间改写更划算。

## 二、可送打磨

按问题分量与可行性排序（算力约束：8×A100 ≤5 天，预研 2×A100）：

"""


def 一句(c, n=110):
    s = c["具体问题"].replace("\n", " ")
    return s if len(s) <= n else s[:n] + "…"


def 结论(c):
    return (c.get("拥挤度") or {}).get("结论") or "未查"


def 关系(c):
    r = c.get("与其他问题的关系") or []
    r = r if isinstance(r, list) else [r]
    return "；".join(x for x in r if "剩余空间改写" in x) or "原卡"


out = [头]
for i, q in enumerate(推荐, 1):
    out.append(f"{i}. **{q}**：{一句(cards[q], 80)}")
out.append("\n第一张建议交给 `/idea-improvement-loop` 的卡：**Q004**。")
out.append(教训)
for i, q in enumerate(推荐, 1):
    out.append(f"{i}. **{q}**（{关系(cards[q])}）——{理由[q]}")

out.append("\n## 三、问题地图\n\n| ID | 问题（截断） | 拥挤度 | 来源 |\n| --- | --- | --- | --- |")
for q, c in cards.items():
    out.append(f"| {q} | {一句(c, 90).replace('|', '／')} | {结论(c)} | {关系(c)} |")
计数 = {}
for c in cards.values():
    计数[结论(c)] = 计数.get(结论(c), 0) + 1
out.append("\n结论统计：" + "，".join(f"{k} {v}" for k, v in sorted(计数.items(), key=lambda x: -x[1])) + "。")

out.append("\n## 四、可送打磨卡详述")
for q in 推荐:
    c = cards[q]; v = c["拥挤度"]
    out.append(f"\n### {q}\n\n**问题。** {c['具体问题']}\n")
    out.append("**证据。**\n")
    for e in c.get("证据") or []:
        eid = e.get("作品ID") or "—"; t = e.get("标题") or ""
        链接 = e.get("原文链接") or (f"https://arxiv.org/abs/{eid}" if eid and eid[0].isdigit() else "")
        内容 = (e.get("内容") or "；".join(f"{k}：{e[k]}" for k in ("证据角色", "实验设置", "具体观察", "对照与保持条件", "证据边界", "位置") if e.get(k))).replace("\n", " ")
        备注 = f"（{e['备注']}）" if e.get("备注") else ""
        out.append(f"- [{eid}]({链接}) {t}：{内容}{备注}")
    out.append(f"\n**为什么判不拥挤。** {v['依据']}\n")
    out.append("**最近邻（查新子代理读取）。**\n")
    for n in v["近邻"]:
        out.append(f"- {n.get('作品ID') or '—'} {n.get('标题') or ''}（{n.get('读取深度')}）：{n.get('覆盖了什么')}")
    out.append(f"\n**可检验切口。** {c['可检验切口']}\n")
    if c.get("已知边界"):
        out.append("**已知边界。** " + "；".join(map(str, c["已知边界"])) + "\n")
    out.append(f"**查询记录。** {'；'.join(v['查询记录'])}")

out.append("\n## 五、其余卡的剩余空间（供下一轮深挖）\n\n| ID | 结论 | 剩余空间 |\n| --- | --- | --- |")
for q, c in cards.items():
    if q in 推荐:
        continue
    v = c.get("拥挤度") or {}
    out.append(f"| {q} | {结论(c)} | {(v.get('剩余空间') or '—').replace('|', '／').replace(chr(10), ' ')} |")

out.append("""
## 六、改写谱系

| 母卡（结论） | 改写卡（结论） |
| --- | --- |""")
for q, c in cards.items():
    r = 关系(c)
    if r != "原卡":
        p = r.split("由 ")[1].split(" ")[0]
        out.append(f"| {p}（{结论(cards[p])}） | {q}（{结论(c)}） |")

out.append("""
## 附录：覆盖与查新方式

- **找卡：** 3 个找卡子任务（后训练、agent 运行时、推理与安全），号段 Q001–Q019、Q020–Q039、Q040–Q059，共三轮；第三轮只看 2610/2611 论文，写出 Q026、Q047。主执行者用号段 Q060+ 从剩余空间改写。旧地图 30 张卡列在 `资料/已审旧卡.txt`，用于避重。
- **查新：** 本轮同时有 3 个查新子代理，各自续用（SendMessage）处理与其已查母卡相关的批次，靠 `资料/查新/近邻台账.jsonl` 共享近邻；共 10 个批次（`资料/查新/批次*.txt`）。技能规范默认只开一个查新子代理，这里为了让改写卡回到持有母卡上下文的子代理而开了 3 个。每张卡的查询记录、近邻与依据见 `资料/查新/结论_<ID>.json`。
- **判据：** 问题级拥挤度（不拥挤／偏拥挤／拥挤／前提不成立），不做 idea 级新意打分；下游打磨仍需针对具体主张查新。
- **读取深度：** 卡内证据由找卡子任务按 Tier B 片段读取；查新子代理在改写卡中新增的近邻标注"由查新子代理读取并登记；主执行者未复读"。查新子代理更正过两处母卡表述：Q040 中 RFEval 降低的是合成指标而非单纯因果影响；Q063 剩余空间中"无需重训"不成立（2610.28303 未公开检查点），已写进 Q071。
- **结构化输出：** `研究问题.json` 由 `.claude/skills/ai-research-landscape/tools/问题卡台账.py export` 合成。
""")

open(f"{slot}/研究地图.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
